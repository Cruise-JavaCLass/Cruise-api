CREATE TABLE dining_restaurants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    location VARCHAR(50) NOT NULL,
    cuisine_type VARCHAR(100),
    max_capacity INTEGER NOT NULL,
    opening_hours VARCHAR(500),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE dining_tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    restaurant_id BIGINT NOT NULL,
    table_number VARCHAR(20) NOT NULL,
    capacity INTEGER NOT NULL,
    table_type VARCHAR(30) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_dining_table_restaurant
        FOREIGN KEY (restaurant_id) REFERENCES dining_restaurants(id),
    CONSTRAINT uk_dining_table_restaurant_number
        UNIQUE (restaurant_id, table_number),
    CONSTRAINT chk_dining_table_capacity
        CHECK (capacity IN (2, 4, 8))
);

CREATE INDEX idx_dining_table_restaurant
    ON dining_tables(restaurant_id);

CREATE TABLE dining_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_code VARCHAR(50) NOT NULL,
    passenger_id BIGINT NOT NULL,
    cabin_number VARCHAR(30) NOT NULL,
    table_id BIGINT NOT NULL,
    reservation_time TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    guest_count INTEGER NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'CONFIRMED',
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,

    CONSTRAINT fk_dining_reservation_table
        FOREIGN KEY (table_id) REFERENCES dining_tables(id),
    CONSTRAINT uk_dining_reservation_code
        UNIQUE (reservation_code)
);

CREATE INDEX idx_dining_reservation_passenger_time
    ON dining_reservations(passenger_id, reservation_time);

CREATE INDEX idx_dining_reservation_table_time
    ON dining_reservations(table_id, reservation_time);

CREATE TABLE guest_dietary_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL,
    allergen_type VARCHAR(30) NOT NULL,
    severity_level VARCHAR(20) NOT NULL,
    special_notes VARCHAR(1000),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_dietary_profile_passenger
    ON guest_dietary_profiles(passenger_id);
