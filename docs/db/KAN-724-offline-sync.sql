-- PostgreSQL additions to the POS-service schema. Existing POS tables must exist.
CREATE TABLE IF NOT EXISTS pos_sync_batches (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 terminal_id VARCHAR(64) NOT NULL, batch_number VARCHAR(128) NOT NULL, request_hash VARCHAR(64) NOT NULL,
 total_records INTEGER NOT NULL, successful_count INTEGER NOT NULL DEFAULT 0,
 failed_count INTEGER NOT NULL DEFAULT 0, duplicate_count INTEGER NOT NULL DEFAULT 0,
 sync_status VARCHAR(32) NOT NULL, response_body TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT uk_sync_terminal_batch UNIQUE(terminal_id,batch_number)
);
CREATE TABLE IF NOT EXISTS pos_sync_idempotency (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 idempotency_key VARCHAR(36) NOT NULL UNIQUE, transaction_reference VARCHAR(128) NOT NULL UNIQUE,
 terminal_id VARCHAR(64) NOT NULL, endpoint VARCHAR(128) NOT NULL, request_hash VARCHAR(64) NOT NULL,
 response_body TEXT, status VARCHAR(16) NOT NULL, expires_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS pos_sync_conflicts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id BIGINT NOT NULL REFERENCES pos_sync_batches(id), idempotency_key VARCHAR(36) NOT NULL UNIQUE,
 transaction_reference VARCHAR(128) NOT NULL, terminal_id VARCHAR(64) NOT NULL, conflict_type VARCHAR(64) NOT NULL,
 server_state_json TEXT NOT NULL, client_state_json TEXT NOT NULL, resolution_status VARCHAR(16) NOT NULL,
 resolved_by VARCHAR(100), resolved_at TIMESTAMPTZ, resolution_reason VARCHAR(512),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_sync_conflict_status ON pos_sync_conflicts(resolution_status,batch_id);
CREATE TABLE IF NOT EXISTS pos_sync_transaction_records (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 batch_id BIGINT NOT NULL REFERENCES pos_sync_batches(id), record_position INTEGER NOT NULL,
 idempotency_key VARCHAR(36) NOT NULL, transaction_reference VARCHAR(128) NOT NULL,
 result_status VARCHAR(16) NOT NULL, server_transaction_id BIGINT, conflict_id BIGINT REFERENCES pos_sync_conflicts(id),
 error_code VARCHAR(128), cabin_number VARCHAR(32),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CONSTRAINT uk_sync_batch_position UNIQUE(batch_id,record_position)
);
