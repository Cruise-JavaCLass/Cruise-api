-- Apply to the same database and search_path as the auth users table.
-- Existing development environments also create this entity via Hibernate ddl-auto=update.
BEGIN;
CREATE TABLE IF NOT EXISTS identity_audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL,
    action VARCHAR(30) NOT NULL,
    actor_user_id BIGINT,
    target_username VARCHAR(50) NOT NULL,
    target_role VARCHAR(30) NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_identity_audit_occurred ON identity_audit_events(occurred_at);
COMMIT;
