 passenger_name VARCHAR(150) NOT NULL, cabin_number VARCHAR(50) NOT NULL, station_code VARCHAR(32) NOT NULL,
 last_observed_station VARCHAR(32), checkin_method VARCHAR(16),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
