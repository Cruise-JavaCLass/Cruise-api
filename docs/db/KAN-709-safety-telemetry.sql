CREATE TABLE IF NOT EXISTS safety_muster_stations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 station_code VARCHAR(32) NOT NULL UNIQUE, muster_leader_staff_id VARCHAR(100) NOT NULL,
 target_lifeboat_number VARCHAR(32) NOT NULL, capacity INTEGER NOT NULL CHECK(capacity>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS safety_deck_zones (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 deck_number INTEGER NOT NULL CHECK(deck_number BETWEEN 1 AND 14), zone_code VARCHAR(100) NOT NULL UNIQUE,
 zone_name VARCHAR(150) NOT NULL, muster_station BOOLEAN NOT NULL DEFAULT FALSE,
 muster_station_code VARCHAR(32) REFERENCES safety_muster_stations(station_code),
 capacity INTEGER NOT NULL CHECK(capacity>0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK((muster_station AND muster_station_code IS NOT NULL) OR (NOT muster_station AND muster_station_code IS NULL))
);
CREATE TABLE IF NOT EXISTS safety_ble_beacons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mac_address VARCHAR(32) NOT NULL UNIQUE, passenger_id BIGINT NOT NULL UNIQUE REFERENCES passengers(id),
 battery_level INTEGER CHECK(battery_level BETWEEN 0 AND 100), last_heartbeat TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS safety_passenger_locations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 passenger_id BIGINT NOT NULL REFERENCES passengers(id), deck_number INTEGER NOT NULL,
 zone_code VARCHAR(100) NOT NULL, rssi_signal_strength INTEGER NOT NULL, recorded_at TIMESTAMPTZ NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_safety_location_latest ON safety_passenger_locations(passenger_id, recorded_at DESC, id DESC);
CREATE TABLE IF NOT EXISTS safety_muster_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 passenger_id BIGINT NOT NULL UNIQUE REFERENCES passengers(id), station_code VARCHAR(32) NOT NULL REFERENCES safety_muster_stations(station_code),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
