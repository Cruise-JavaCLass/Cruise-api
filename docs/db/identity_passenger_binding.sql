-- Apply to the same database and search_path as the auth users table.
-- Existing development environments also create this entity via Hibernate ddl-auto=update.
BEGIN;
CREATE TABLE IF NOT EXISTS user_passenger_bindings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    passenger_id BIGINT NOT NULL,
    booking_reference VARCHAR(100) NOT NULL,
    cabin_number VARCHAR(20) NOT NULL,
    verification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_user_passenger_binding_user_booking UNIQUE (user_id, booking_reference),
    CONSTRAINT uk_user_passenger_binding_passenger UNIQUE (passenger_id)
);
CREATE INDEX IF NOT EXISTS idx_upb_user_id ON user_passenger_bindings(user_id);
CREATE INDEX IF NOT EXISTS idx_upb_passenger_id ON user_passenger_bindings(passenger_id);
CREATE INDEX IF NOT EXISTS idx_upb_booking_ref ON user_passenger_bindings(booking_reference);
COMMIT;
